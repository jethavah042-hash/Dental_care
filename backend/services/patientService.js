const mongoose = require("mongoose");
const Patient = require("../models/Patient");

// ─── Create Patient ───────────────────────────────────────────────────────────
/**
 * Creates a new patient record.
 * patientId is auto-generated by the Patient model pre-validate hook.
 * createdBy stores the authenticated admin/receptionist's userId.
 *
 * @param {Object} data     - validated patient fields from request body
 * @param {string} createdBy - req.user._id (admin or receptionist)
 * @returns {Object}         - { patient }
 * @throws  {Error}          - with statusCode
 */
const createPatient = async (data, createdBy) => {
  const {
    fullName, email, phone, dateOfBirth, gender, bloodGroup,
    profileImage, address, emergencyContact,
    medicalHistory, allergies, currentMedications, notes,
    userId,
  } = data;

  // Normalize email
  const normalizedEmail = email ? email.trim().toLowerCase() : null;

  // Create patient — patientId auto-set by pre-validate hook
  const patient = await Patient.create({
    fullName: fullName.trim(),
    email: normalizedEmail,
    phone: phone.trim(),
    dateOfBirth: dateOfBirth || null,
    gender: gender || null,
    bloodGroup: bloodGroup || null,
    profileImage: profileImage || null,
    address: address || {},
    emergencyContact: emergencyContact || {},
    medicalHistory: medicalHistory || null,
    allergies: allergies || null,
    currentMedications: currentMedications || null,
    notes: notes || null,
    userId: userId || null,
    createdBy,
  });

  // Populate createdBy for clean response
  await patient.populate("createdBy", "fullName email role");

  return { patient };
};

// ─── Get All Patients ─────────────────────────────────────────────────────────
/**
 * Returns paginated patient list with optional search, filter, and sort.
 *
 * @param {Object} queryParams - { page, limit, search, gender, isActive, city, sortBy, sortOrder }
 * @returns {Object}           - { patients, pagination }
 */
const getAllPatients = async (queryParams) => {
  const {
    page = 1,
    limit = 10,
    search = "",
    gender,
    isActive,
    city,
    sortBy = "registrationDate",
    sortOrder = "desc",
  } = queryParams;

  // ── Build filter object ──────────────────────────────────────────────────────
  const filter = {};

  // Active/inactive filter
  if (isActive !== undefined && isActive !== "") {
    filter.isActive = isActive === "true" || isActive === true;
  }

  // Gender filter
  if (gender) {
    filter.gender = gender;
  }

  // City filter
  if (city) {
    filter["address.city"] = { $regex: city.trim(), $options: "i" };
  }

  // Search: patientId | fullName | email | phone
  // Safe: only use $regex with anchored/escaped input — no $ operators from client
  if (search && search.trim() !== "") {
    const safeSearch = search.trim().replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    filter.$or = [
      { patientId: { $regex: safeSearch, $options: "i" } },
      { fullName:  { $regex: safeSearch, $options: "i" } },
      { email:     { $regex: safeSearch, $options: "i" } },
      { phone:     { $regex: safeSearch, $options: "i" } },
    ];
  }

  // ── Pagination ───────────────────────────────────────────────────────────────
  const pageNum  = Math.max(1, parseInt(page)  || 1);
  const limitNum = Math.min(100, Math.max(1, parseInt(limit) || 10));
  const skip     = (pageNum - 1) * limitNum;

  // ── Sort ─────────────────────────────────────────────────────────────────────
  const allowedSortFields = ["fullName", "registrationDate", "createdAt", "patientId"];
  const sortField = allowedSortFields.includes(sortBy) ? sortBy : "registrationDate";
  const sortDirection = sortOrder === "asc" ? 1 : -1;
  const sortObj = { [sortField]: sortDirection };

  // ── Execute queries in parallel ───────────────────────────────────────────────
  const [patients, totalPatients] = await Promise.all([
    Patient.find(filter)
      .select("-medicalHistory -allergies -currentMedications -notes") // list view: exclude medical details
      .populate("createdBy", "fullName role")
      .sort(sortObj)
      .skip(skip)
      .limit(limitNum)
      .lean(),
    Patient.countDocuments(filter),
  ]);

  const totalPages = Math.ceil(totalPatients / limitNum);

  return {
    patients,
    pagination: {
      totalPatients,
      currentPage: pageNum,
      totalPages,
      limit: limitNum,
      hasNextPage: pageNum < totalPages,
      hasPrevPage: pageNum > 1,
    },
  };
};

// ─── Get Patient By ID ────────────────────────────────────────────────────────
/**
 * Returns full patient details by MongoDB ObjectId.
 * Medical details included — caller (controller) controls what to expose per role.
 *
 * @param {string} id - MongoDB ObjectId string
 * @returns {Object}  - { patient }
 * @throws  {Error}   - with statusCode
 */
const getPatientById = async (id) => {
  if (!mongoose.Types.ObjectId.isValid(id)) {
    const error = new Error("Invalid patient ID format.");
    error.statusCode = 400;
    throw error;
  }

  const patient = await Patient.findById(id)
    .populate("createdBy", "fullName role email")
    .populate("userId", "fullName email phone role isActive");

  if (!patient) {
    const error = new Error("Patient not found.");
    error.statusCode = 404;
    throw error;
  }

  return { patient };
};

// ─── Update Patient ───────────────────────────────────────────────────────────
/**
 * Updates allowed patient fields.
 * patientId, userId, createdBy are protected — cannot be changed.
 *
 * @param {string} id      - MongoDB ObjectId
 * @param {Object} updates - validated fields to update
 * @returns {Object}       - { patient }
 * @throws  {Error}        - with statusCode
 */
const updatePatient = async (id, updates) => {
  if (!mongoose.Types.ObjectId.isValid(id)) {
    const error = new Error("Invalid patient ID format.");
    error.statusCode = 400;
    throw error;
  }

  // Whitelist: only these top-level fields can be updated
  const allowedFields = [
    "fullName", "email", "phone", "dateOfBirth", "gender", "bloodGroup",
    "profileImage", "address", "emergencyContact",
    "medicalHistory", "allergies", "currentMedications", "notes",
  ];

  // Build safe update object — strip any disallowed fields
  const safeUpdates = {};
  for (const key of allowedFields) {
    if (updates[key] !== undefined) {
      safeUpdates[key] = updates[key];
    }
  }

  // Handle nested address update (merge, don't replace)
  if (safeUpdates.email) {
    safeUpdates.email = safeUpdates.email.trim().toLowerCase();
  }

  const patient = await Patient.findByIdAndUpdate(
    id,
    { $set: safeUpdates },
    { new: true, runValidators: true }
  ).populate("createdBy", "fullName role");

  if (!patient) {
    const error = new Error("Patient not found.");
    error.statusCode = 404;
    throw error;
  }

  return { patient };
};

// ─── Update Patient Status ────────────────────────────────────────────────────
/**
 * Soft-activates or soft-deactivates a patient (admin only).
 * Medical records are NEVER deleted.
 *
 * @param {string}  id       - MongoDB ObjectId
 * @param {boolean} isActive - true or false
 * @returns {Object}         - { patient }
 * @throws  {Error}          - with statusCode
 */
const updatePatientStatus = async (id, isActive) => {
  if (!mongoose.Types.ObjectId.isValid(id)) {
    const error = new Error("Invalid patient ID format.");
    error.statusCode = 400;
    throw error;
  }

  const patient = await Patient.findByIdAndUpdate(
    id,
    { $set: { isActive } },
    { new: true }
  ).select("-medicalHistory -allergies -currentMedications -notes");

  if (!patient) {
    const error = new Error("Patient not found.");
    error.statusCode = 404;
    throw error;
  }

  return { patient };
};

// ─── Patient Statistics ───────────────────────────────────────────────────────
/**
 * Returns real MongoDB-based statistics using aggregation.
 * No hardcoded numbers.
 *
 * @returns {Object} - { stats }
 */
const getPatientStats = async () => {
  // Start of current month
  const startOfMonth = new Date();
  startOfMonth.setDate(1);
  startOfMonth.setHours(0, 0, 0, 0);

  const [result] = await Patient.aggregate([
    {
      $group: {
        _id: null,
        totalPatients:    { $sum: 1 },
        activePatients:   { $sum: { $cond: ["$isActive", 1, 0] } },
        inactivePatients: { $sum: { $cond: ["$isActive", 0, 1] } },
        newThisMonth: {
          $sum: {
            $cond: [
              { $gte: ["$registrationDate", startOfMonth] },
              1,
              0,
            ],
          },
        },
      },
    },
    {
      $project: {
        _id: 0,
        totalPatients: 1,
        activePatients: 1,
        inactivePatients: 1,
        newThisMonth: 1,
      },
    },
  ]);

  // If no patients exist yet, return zeros
  const stats = result || {
    totalPatients: 0,
    activePatients: 0,
    inactivePatients: 0,
    newThisMonth: 0,
  };

  return { stats };
};

module.exports = {
  createPatient,
  getAllPatients,
  getPatientById,
  updatePatient,
  updatePatientStatus,
  getPatientStats,
};
